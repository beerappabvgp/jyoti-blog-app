import mongoose from "mongoose";
import { maxLength, required } from "zod/mini";

const Schema = mongoose.Schema;

const UserSchema = new Schema({
    username: {
        type: String,
        required: true,
        unique: true,
    },
    email: {
        type: String,
        unique: true,
        required: true,
    },
    contact: {
        type: String,
        required: true,
    },
    password: {
        type: String,
        required: true,
    },
    bio: {
        type: String,
        maxLength: 200,
    },
});

export const UserModel = mongoose.model('users', UserSchema);